func translate(language, key string, args ...any) string {
	index := 0
	if language == "en" {
		index = 1
	}
	value, ok := stringsTable[key]
	if !ok {
		panic("desktop: missing translation key " + key)
	}
	if len(args) == 0 {
		return value[index]
	}
	return fmt.Sprintf(value[index], args...)
}
